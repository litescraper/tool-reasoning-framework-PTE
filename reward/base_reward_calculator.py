import json
from abc import abstractmethod
from json import JSONDecodeError


class BaseRewardCalculator:
    """Base class for reward calculation."""

    @abstractmethod
    def extract_output(output_str: str):
        """
        Extract information from output string for reward calculation.
        
        Args:
            output_str: Final response
            
        Returns:
            Extracted information for reward calculation
        """
        pass
    
    @abstractmethod
    def _verify_correction(self, extract_solution: dict, identity: dict, **kwargs) -> float:
        """
        Verify the extracted solution against the ground truth and compute a correctness score.
        """
        pass
    
    @classmethod
    def verify_score(cls, model_output, identity: dict, format_score=0, short_penalty=False, 
                     short_threshold=256, think_threshold=0, ans_threshold=256, 
                     format_penalty=False, **kwargs) -> float:
        """
        Verify the model output against the ground truth and compute a correctness score.
        
        Args:
            model_output (str): The full output string generated by the model.
            identity (dict): Ground truth or reference information used for verification.
            format_score (float): Base score awarded for correct output format.
            short_penalty (bool): Whether to apply a penalty if the output is too short.
            short_threshold (int): Minimum total length of the model output to avoid penalty.
            think_threshold (int): Minimum length required for the reasoning section.
            ans_threshold (int): Minimum length required for the final answer.
            format_penalty (bool): If True, enforces strict formatting rules.
            
        Returns:
            float: A score between 0 and 1 representing the correctness of the model output.
        """
        score = 0.
        
        # Ensure identity is a dict
        if not isinstance(identity, dict):
            try:
                identity = json.loads(identity)
            except (JSONDecodeError, TypeError):
                pass
            except Exception as e:
                print(f"[DEBUG BaseRewardCalculator] Error in verify_score: identity is not a dict")
                return 0.0
        
        # Format validation
        if format_penalty and ("<think>" not in model_output or "</think>" not in model_output):
            return score
        if format_penalty and (model_output.count("<think>") > 1 or 
                              model_output.count("</think>") > 1 or 
                              model_output.count("<think>") != model_output.count("</think>") or 
                              not model_output.startswith("<think>") or 
                              model_output.endswith("</think>")):
            return score
        
        try:
            extract_solution = cls.extract_output(model_output)
            if extract_solution is None:
                return score
            else:
                score = format_score  # Must assign format_score here!
            judge = cls._verify_correction(extract_solution, identity, **kwargs)
            if type(judge) == bool and judge:
                score = 1.
            else:
                # More lenient type checking, accept numeric types
                if isinstance(judge, (bool, int, float)):
                    score = float(judge)
                else:
                    print(f"[DEBUG BaseRewardCalculator] Warning: _verify_correction returned unexpected type {type(judge)}: {judge}")
                    score = 0.0
        except Exception as e:
            print(f"[DEBUG BaseRewardCalculator] Error in verify_score: {str(e)}")
            import traceback
            print(f"[DEBUG BaseRewardCalculator] Exception traceback:\n{traceback.format_exc()}")
            return 0.0
        
        ans_output = model_output.rsplit("</think>", 1)[1] if "</think>" in model_output else ""
        think_length = len(model_output) - len(ans_output)
        score = max(0, score)  # Ensure score is non-negative
        
        if (short_penalty and len(model_output) < short_threshold) or \
           (short_penalty and len(ans_output) < ans_threshold) or \
           (short_penalty and think_length < think_threshold):
            # If the output is too short, consider it incorrect
            return min(score * len(model_output) / short_threshold, 
                      score * len(ans_output) / ans_threshold, 
                      score * think_length / think_threshold)
        
        return score

